#!/usr/bin/env node
import { readFile, readdir, writeFile, mkdir } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const SKILLS_DIR = join(ROOT, ".claude", "skills");
const OUT = join(ROOT, "src", "marketing", "generated", "skills.ts");

const entries = (await readdir(SKILLS_DIR, { withFileTypes: true }))
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const map = {};
for (const name of entries) {
  const path = join(SKILLS_DIR, name, "SKILL.md");
  map[name] = await readFile(path, "utf8");
}

const body = `// Generated by scripts/build-skills-index.mjs. Do not edit.
export const BUNDLED_SKILLS: Record<string, string> = ${JSON.stringify(map, null, 2)} as const;

export const BUNDLED_SKILL_NAMES: readonly string[] = ${JSON.stringify(entries, null, 2)} as const;
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, body, "utf8");
console.log(`wrote ${OUT} with ${entries.length} skills`);
